function getLiteralUnionOptions(type: ts.Type) {
  if (!type.isUnion()) {
    return null;
  }

  const options: string[] = [];

  for (const item of type.types) {
    if (item.flags & ts.TypeFlags.Undefined) {
      continue;
    }

    if (!item.isStringLiteral()) {
      return null;
    }

    options.push(item.value);
  }

  return options.length > 0 ? options : null;
}

function extractComponentProps(name: string): ExtractedProp[] {
  const sourceFilePath = findTypeSourceFile(
    name.charAt(0).toLowerCase() + name.slice(1)
  );

  if (!sourceFilePath) {
    console.log(`⚠️ Types source not found for ${name}`);
    return [];
  }

  const program = createTypesProgram();
  const checker = program.getTypeChecker();

  const sourceFile = program.getSourceFile(sourceFilePath);

  if (!sourceFile) {
    return [];
  }

  const typeNames = [`Base${name}Props`, `${name}BaseProps`];

  const moduleSymbol = checker.getSymbolAtLocation(sourceFile);

  if (!moduleSymbol) {
    console.log(`⚠️ Module symbol not found for ${sourceFilePath}`);
    return [];
  }

  const exportedSymbol = checker
    .getExportsOfModule(moduleSymbol)
    .find((symbol) => typeNames.includes(symbol.name));

  if (!exportedSymbol) {
    console.log(`⚠️ Export ${typeNames.join(' or ')} not found.`);
    return [];
  }

  const declaredType = checker.getDeclaredTypeOfSymbol(exportedSymbol);

  const propSymbols = checker.getPropertiesOfType(declaredType);

  const extracted: ExtractedProp[] = [];

  for (const propSymbol of propSymbols) {
    const declaration =
      propSymbol.valueDeclaration ?? propSymbol.declarations?.[0];

    if (!declaration) {
      continue;
    }

    const propName = propSymbol.name;

    const required = (propSymbol.flags & ts.SymbolFlags.Optional) === 0;

    const type = checker.getTypeOfSymbolAtLocation(propSymbol, declaration);

    const typeText = checker.typeToString(
      type,
      declaration,
      ts.TypeFormatFlags.NoTruncation
    );

    const description = ts.displayPartsToString(
      propSymbol.getDocumentationComment(checker)
    );

    const unionOptions = getLiteralUnionOptions(type);

    if (unionOptions) {
      extracted.push({
        name: propName,
        kind: 'select',
        required,
        type: typeText,
        description,
        sourceFilePath: declaration.getSourceFile().fileName,
        options: unionOptions,
      });

      continue;
    }

    const nonNullableType = checker.getNonNullableType(type);

    if (nonNullableType.flags & ts.TypeFlags.Boolean) {
      extracted.push({
        name: propName,
        kind: 'boolean',
        required,
        type: typeText,
        description,
        sourceFilePath: declaration.getSourceFile().fileName,
      });

      continue;
    }

    if (
      nonNullableType.flags & ts.TypeFlags.String ||
      nonNullableType.flags & ts.TypeFlags.StringLiteral
    ) {
      extracted.push({
        name: propName,
        kind: 'string',
        required,
        type: typeText,
        description,
        sourceFilePath: declaration.getSourceFile().fileName,
      });

      continue;
    }

    if (
      nonNullableType.flags & ts.TypeFlags.Number ||
      nonNullableType.flags & ts.TypeFlags.NumberLiteral
    ) {
      extracted.push({
        name: propName,
        kind: 'number',
        required,
        type: typeText,
        description,
        sourceFilePath: declaration.getSourceFile().fileName,
      });

      continue;
    }

    extracted.push({
      name: propName,
      kind: 'other',
      required,
      type: typeText,
      description,
      sourceFilePath: declaration.getSourceFile().fileName,
    });
  }

  return extracted;
}

function extractExportedProps(params: {
  sourceFilePath: string;
  exportName: string;
  program: ts.Program;
}): ExtractedProp[] {
  const { sourceFilePath, exportName, program } = params;

  const checker = program.getTypeChecker();
  const sourceFile = program.getSourceFile(sourceFilePath);

  if (!sourceFile) {
    return [];
  }

  const moduleSymbol = checker.getSymbolAtLocation(sourceFile);

  if (!moduleSymbol) {
    return [];
  }

  const exportedSymbol = checker
    .getExportsOfModule(moduleSymbol)
    .find((symbol) => symbol.name === exportName);

  if (!exportedSymbol) {
    console.log(`⚠️ Export ${exportName} not found in ${sourceFilePath}`);
    return [];
  }

  const declaredType = checker.getDeclaredTypeOfSymbol(exportedSymbol);
  const propSymbols = checker.getPropertiesOfType(declaredType);

  const extracted: ExtractedProp[] = [];

  for (const propSymbol of propSymbols) {
    const declaration =
      propSymbol.valueDeclaration ?? propSymbol.declarations?.[0];

    if (!declaration) continue;

    const type = checker.getTypeOfSymbolAtLocation(propSymbol, declaration);

    const typeText = checker.typeToString(
      type,
      declaration,
      ts.TypeFormatFlags.NoTruncation
    );

    const description = ts.displayPartsToString(
      propSymbol.getDocumentationComment(checker)
    );

    const unionOptions = getLiteralUnionOptions(type);
    const nonNullableType = checker.getNonNullableType(type);

    let kind: ExtractedProp['kind'] = 'other';

    if (unionOptions) {
      kind = 'select';
    } else if (nonNullableType.flags & ts.TypeFlags.Boolean) {
      kind = 'boolean';
    } else if (
      nonNullableType.flags & ts.TypeFlags.String ||
      nonNullableType.flags & ts.TypeFlags.StringLiteral
    ) {
      kind = 'string';
    } else if (
      nonNullableType.flags & ts.TypeFlags.Number ||
      nonNullableType.flags & ts.TypeFlags.NumberLiteral
    ) {
      kind = 'number';
    }

    extracted.push({
      name: propSymbol.name,
      kind,
      required: (propSymbol.flags & ts.SymbolFlags.Optional) === 0,
      type: typeText,
      description,
      sourceFilePath: declaration.getSourceFile().fileName,
      ...(unionOptions ? { options: unionOptions } : {}),
    });
  }

  return extracted;
}

