function inferComponentProfile(name: string): ComponentProfile {
  if (['Modal', 'Popover', 'Tooltip', 'Dropdown'].includes(name)) {
    return 'overlay';
  }

  if (['Tabs'].includes(name)) {
    return 'navigation';
  }

  if (['Select'].includes(name)) {
    return 'compound';
  }

  if (['Radio', 'Checkbox'].includes(name)) {
    return 'selection-control';
  }

  if (['Input', 'FormField'].includes(name)) {
    return 'form-control';
  }

  return 'primitive';
}

