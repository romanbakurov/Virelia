function findTypeSourceFile(name: string) {
  const candidates = [
    path.join(typesRoot, `${name}.ts`),
    path.join(typesRoot, `${name.charAt(0).toLowerCase()}${name.slice(1)}.ts`),
  ];

  return candidates.find((filePath) => fs.existsSync(filePath));
}

function findPlatformTypeSourceFile(
  platform: Platform,
  name: string
): string | undefined {
  const packageName = platform === 'react' ? 'react' : 'react-native';

  const packageRoot = path.join(root, 'packages', packageName, 'src');
  const stack = [packageRoot];

  while (stack.length > 0) {
    const current = stack.pop();

    if (!current) continue;

    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const fullPath = path.join(current, entry.name);

      if (entry.isDirectory()) {
        stack.push(fullPath);
        continue;
      }

      if (
        entry.name === 'types.ts' &&
        path.basename(path.dirname(fullPath)) === name
      ) {
        return fullPath;
      }
    }
  }

  return undefined;
}

function listPlatformTypeSourceFiles(platform: Platform) {
  const packageName = platform === 'react' ? 'react' : 'react-native';
  const packageRoot = path.join(root, 'packages', packageName, 'src');
  const stack = [packageRoot];
  const files: string[] = [];

  while (stack.length > 0) {
    const current = stack.pop();

    if (!current) continue;

    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const fullPath = path.join(current, entry.name);

      if (entry.isDirectory()) {
        stack.push(fullPath);
        continue;
      }

      if (entry.name === 'types.ts') {
        files.push(fullPath);
      }
    }
  }

  return files;
}

